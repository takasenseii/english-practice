export function applyMcqReview(materials) {
  function visit(value) {
    if (!value || typeof value !== 'object') return;
    if (value.type === 'multiple-choice' && reviewed[value.id]) Object.assign(value, reviewed[value.id]);
    for (const child of Object.values(value)) if (child && typeof child === 'object') visit(child);
  }
  visit(materials);
  return materials;
}

export function indexedOptions(options, random = Math.random) {
  const result = options.map((label, index) => ({label, index}));
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}
